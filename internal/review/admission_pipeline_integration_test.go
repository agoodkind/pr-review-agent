func TestReviewBudgetPreservesRelationshipWorkOutsideTheContentCap(t *testing.T) {
	file, initial := relationshipGitInput(t)
	policy := policytest.Load(t)
	model := openai.NewClient(config.Config{ReviewPolicy: policy, MinimumImportance: 5, ReviewModel: "configured-model"}, nil)
	var data reviewrules.PromptData
	required, err := policy.Render("omissions.none", data)
	if err != nil {
		t.Fatal(err)
	}
	bounded, err := review.BoundModelReviewChunksWithContext(model, initial, []diff.FileContext{file}, 5, required, "", policy, config.MaximumPromptBytes)
	if err != nil {
		t.Fatal(err)
	}
	prepared, err := review.PrepareRelationshipChunks(model, bounded, []diff.FileContext{file}, 5, required, "", policy, config.MaximumPromptBytes)
	if err != nil || len(prepared) <= len(bounded) {
		t.Fatalf("The real source did not retain its required relationship assessments: %v", err)
	}
	decision := review.CheckReviewBudget(1, prepared, 100, len(bounded))
	if decision.Skip || decision.ReviewableChunks != len(bounded) {
		t.Fatalf("Derived relationship work rejected content within its configured cap: %+v; source=%d total=%d", decision, len(bounded), len(prepared))
	}
	if !review.CheckReviewBudget(1, prepared, 100, len(bounded)-1).Skip {
		t.Fatal("The content cap did not reject ordinary requests above its boundary.")
	}
	if !review.CheckReviewBudget(301, prepared, 1000, 60).Skip {
		t.Fatal("The public budget check changed the existing GitHub file limit.")
	}
	const gapBytes = 4096
	metadata := diff.PullRequestMetadata(githubapp.PullRequest{Body: strings.Repeat("x", gapBytes+1)}, nil)
	gap, err := diff.ChunkInput(diff.ReviewInput{Metadata: metadata}, gapBytes)
	if err != nil || len(gap) != 1 || gap[0].CoverageComplete {
		t.Fatalf("The actual oversized prose did not produce an explicit scope gap: %v", err)
	}
	if result := review.CheckReviewBudget(1, gap, 100, 1); result.Skip || result.ReviewableChunks != 0 {
		t.Fatalf("A placeholder consumed the ordinary content cap: %+v", result)
	}
	mixed, err := diff.ChunkInput(diff.ReviewInput{Files: []diff.FileContext{file}, Metadata: metadata}, gapBytes)
	if err != nil || len(mixed) != 1 || mixed[0].CoverageComplete {
		t.Fatalf("The source and oversized prose did not retain their mixed assessment: %v", err)
	}
	if result := review.CheckReviewBudget(1, mixed, 100, 1); result.Skip || result.ReviewableChunks != 1 {
		t.Fatalf("A mixed gap concealed required ordinary source from the content cap: %+v", result)
	}
	t.Logf("The public budget admits %d ordinary requests while preserving %d total assessments.", decision.ReviewableChunks, len(prepared))
}

func TestReviewBudgetExcludesFiveThousandGeneratedHunksBeforeThirtySourceRequests(t *testing.T) {
	const generatedHunks = 5000
	const sourceFiles = 30
	const changedLiteralBytes = 65536
	var before, after strings.Builder
	for _, destination := range []*strings.Builder{&before, &after} {
		destination.WriteString("// Code generated by fixture; DO NOT EDIT.\npackage generated\n")
	}
	for index := range generatedHunks {
		fmt.Fprintf(&before, "var value%d = 0\n// Keep generated record %d.\n", index, index)
		fmt.Fprintf(&after, "var value%d = 1\n// Keep generated record %d.\n", index, index)
	}
	generated := classificationGitFile(t, "generated.go", before.String(), after.String())
	hunks := strings.Count(generated.Patch, "@@ -")
	if hunks != generatedHunks {
		t.Fatalf("The real Git diff produced %d generated hunks rather than %d.", hunks, generatedHunks)
	}
	files := []diff.FileContext{generated}
	for index := range sourceFiles {
		content := "package sample\nconst value = \"" + strings.Repeat("x", changedLiteralBytes) + "\"\n"
		files = append(files, classificationGitFile(t, fmt.Sprintf("source_%02d.go", index), "package sample\nconst value = \"before\"\n", content))
	}
	policy := policytest.Load(t)
	input := diff.ReviewInput{Files: files}
	decisions, unresolved, err := review.PlanFileAssessments(input, policy)
	if err != nil || len(unresolved) != 0 {
		t.Fatalf("The generated marker and handwritten source did not establish their review scope: %v", err)
	}
	planned, _, err := review.PlanFileContentReview(input, decisions, policy)
	if err != nil || len(planned.Files) != sourceFiles {
		t.Fatalf("The content plan did not exclude generated hunks before chunking: %v", err)
	}
	for _, file := range planned.Files {
		if file.Path == generated.Path {
			t.Fatal("The content plan retained generated output for review.")
		}
	}
	model := openai.NewClient(config.Config{ReviewPolicy: policy, MinimumImportance: 5, ReviewModel: "configured-model"}, nil)
	overhead, err := model.ReviewRequestBytes("")
	if err != nil {
		t.Fatal(err)
	}
	seedMaximum := overhead + 16*changedLiteralBytes
	seed, err := diff.ChunkInput(diff.ReviewInput{Files: planned.Files[:1]}, seedMaximum)
	if err != nil || len(seed) != 1 {
		t.Fatalf("The source sizing sample did not produce one complete chunk: %v", err)
	}
	seedPrompt, err := review.BuildPrompt(seed[0], 5, "", policy, seedMaximum)
	if err != nil {
		t.Fatal(err)
	}
	seedBytes, err := model.ReviewRequestBytes(seedPrompt)
	if err != nil {
		t.Fatal(err)
	}
	maximumBytes := seedBytes + 1024
	chunks, err := diff.ChunkInput(planned, maximumBytes)
	if err != nil {
		t.Fatal(err)
	}
	chunks, err = review.BoundModelReviewChunks(model, chunks, planned.Files, 5, "", policy, maximumBytes)
	if err != nil || len(chunks) != sourceFiles {
		t.Fatalf("The SDK budget did not produce thirty reviewable source requests: chunks=%d error=%v", len(chunks), err)
	}
	for _, chunk := range chunks {
		if !chunk.CoverageComplete {
			t.Fatal("A required handwritten source request became a placeholder.")
		}
	}
	decision := review.CheckReviewBudget(len(planned.Files), chunks, 100, 60)
	if decision.Skip || decision.ReviewableChunks != sourceFiles {
		t.Fatalf("Generated changes consumed the ordinary content budget: %+v", decision)
	}
	metadata := diff.PullRequestMetadata(githubapp.PullRequest{Title: "Review source changes"}, nil)
	metadataChunks, err := diff.ChunkInput(diff.ReviewInput{Metadata: metadata}, maximumBytes)
	if err != nil {
		t.Fatal(err)
	}
	if !review.CheckReviewBudget(len(planned.Files), append(chunks, metadataChunks...), 100, sourceFiles).Skip {
		t.Fatal("Required metadata requests did not count toward the ordinary content cap.")
	}
	t.Logf("The actual Git diff contains %d excluded generated hunks; the SDK prepares %d admitted source requests.", hunks, decision.ReviewableChunks)
}

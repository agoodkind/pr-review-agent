func TestPreflightPreservesOneHundredCompletedAssessmentsWithinTheCommentLimit(t *testing.T) {
	files := classificationGitSources(t, 100, reviewrules.ContentSource)
	input := diff.ReviewInput{Files: files}
	policy := policytest.Load(t)
	decisions, unresolved, err := review.PlanFileAssessments(input, policy)
	if err != nil || len(unresolved) != 0 || len(decisions) != len(files) {
		t.Fatalf("Every changed source file requires a durable assessment before review: %v", err)
	}
	uncompleted, err := json.Marshal(decisions)
	if err != nil {
		t.Fatal(err)
	}
	const prefix = "<!-- pr-review-agent:file-assessments:v1 "
	initialSize := len(prefix) + base64.RawURLEncoding.EncodedLen(len(uncompleted)) + len(" -->")
	limited := assessmentPolicyStorageLimit(t, initialSize)
	if _, _, err := review.PlanFileAssessments(input, limited); !errors.Is(err, review.ErrAssessmentIncomplete) {
		t.Fatal("Persistence validation must reserve the completed review fields before starting content review.")
	}
	for index := range decisions {
		decisions[index].Reviewed = true
	}
	summary := review.Summary{
		FileAssessments: decisions, FileAssessmentMaximumBytes: policy.FileAssessmentMaximumBytes(),
		FileAssessmentsDisplay: reviewrules.FindingsCollapsed, CoverageComplete: true,
		Decision: domain.ReviewDecisionApprove,
	}
	body := review.RenderBody(summary)
	if len(body) > 65536 {
		t.Fatalf("The complete summary requires %d bytes and exceeds the GitHub comment limit.", len(body))
	}
	_, encoded, found := strings.Cut(body, prefix)
	if !found {
		t.Fatal("The completed summary must retain every file assessment.")
	}
	encoded, _, _ = strings.Cut(encoded, " -->")
	data, err := base64.RawURLEncoding.DecodeString(encoded)
	if err != nil {
		t.Fatal(err)
	}
	var restored []domain.FileAssessment
	if err := json.Unmarshal(data, &restored); err != nil {
		t.Fatal(err)
	}
	if len(restored) != len(files) {
		t.Fatal("The completed summary omitted file assessments.")
	}
	for _, assessment := range restored {
		if !assessment.Reviewed {
			t.Fatal("The completed summary lost a completed source assessment.")
		}
	}
	t.Logf("The complete summary preserves %d assessments in %d bytes.", len(restored), len(body))
}

func classificationGitSources(t *testing.T, count int, kind reviewrules.ContentKind) []diff.FileContext {
	t.Helper()
	directory := t.TempDir()
	command := func(arguments ...string) string {
		t.Helper()
		process := exec.CommandContext(t.Context(), "git", arguments...)
		process.Dir = directory
		output, err := process.CombinedOutput()
		if err != nil {
			t.Fatalf("Git %s failed: %v\n%s", arguments[0], err, output)
		}
		return string(output)
	}
	command("init", "--quiet")
	before, after, extension := "package sample\nconst Value = 1\n", "package sample\nconst Value = 2\n", "go"
	switch kind {
	case reviewrules.ContentSource:
	case reviewrules.ContentGenerated:
		after = "// Code generated by integration; DO NOT EDIT.\npackage sample\nconst Value = 2\n"
	case reviewrules.ContentBinary:
		before, after, extension = "\x00earlier bytes", "\x00updated bytes", "bin"
	default:
		t.Fatal("The Git input requires a supported classification kind.")
	}
	for index := range count {
		name := fmt.Sprintf("file%03d.%s", index, extension)
		if err := os.WriteFile(filepath.Join(directory, name), []byte(before), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	command("add", ".")
	command("-c", "user.name=Integration Test", "-c", "user.email=integration@example.invalid", "-c", "commit.gpgsign=false", "-c", "core.hooksPath=/dev/null", "commit", "--quiet", "-m", "Create classification source\n\nCo-authored-by: Codex <noreply@openai.com>")
	var files []diff.FileContext
	for index := range count {
		name := fmt.Sprintf("file%03d.%s", index, extension)
		if err := os.WriteFile(filepath.Join(directory, name), []byte(after), 0o600); err != nil {
			t.Fatal(err)
		}
		patch := command("diff", "--unified=0", "--", name)
		lines, hunks, err := diff.ChangedRightLines(patch)
		if err != nil {
			t.Fatal(err)
		}
		files = append(files, diff.FileContext{Path: name, Status: "modified", Patch: patch, CurrentContent: after, ChangedRightLines: lines, ChangedRightHunks: hunks, CoverageComplete: true})
	}
	return files
}

func TestPreflightExcludesArtifactsBeforeCreatingContentRequests(t *testing.T) {
	lockfile := classificationGitFile(t, "package-lock.json", "{}\n", "{\"artifact_record\":\"excluded-lockfile-body\"}\n")
	generated := classificationGitFile(t, "generated.go", "package sample\n", "// Code generated by sample; DO NOT EDIT.\npackage sample\nconst Artifact = \"excluded-generated-body\"\n")
	manifest := classificationGitFile(t, "package.json", "{}\n", "{\"dependencies\":{\"changed-package\":\"2.0.0\"}}\n")
	vendor := classificationGitFile(t, "vendor/library/source.go", "package library\n", "package library\nconst Artifact = \"excluded-vendor-body\"\n")
	compiled := classificationGitFile(t, "program.class", "earlier compiled bytes\n", "excluded-compiled-body\n")
	binary := classificationGitFile(t, "asset.bin", "\x00earlier bytes", "\x00excluded-binary-body")
	input := diff.ReviewInput{Files: []diff.FileContext{lockfile, generated, manifest, vendor, compiled, binary}}
	policy := policytest.Load(t)
	decisions, unresolved, err := review.PlanFileAssessments(input, policy)
	if err != nil {
		t.Fatal(err)
	}
	if len(unresolved) != 0 || len(decisions) != len(input.Files) {
		t.Fatal("Trusted artifact evidence and recognized source require complete deterministic assessments.")
	}
	planned, _, err := review.PlanFileContentReview(input, decisions, policy)
	if err != nil {
		t.Fatal(err)
	}
	if len(planned.Files) != 1 || planned.Files[0].Path != manifest.Path {
		t.Fatal("Content review must retain the changed dependency manifest and exclude artifact bodies.")
	}
	assertPlannedChangedRows(t, planned, manifest)
	model := openai.NewClient(config.Config{ReviewPolicy: policy, MinimumImportance: 7, ReviewModel: "configured-model"}, nil)
	prompt, err := review.BuildFileAssessmentPrompt(model, githubapp.PullRequest{}, input.Files, manifest.Path, policy, config.MaximumPromptBytes, decisions)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(prompt, "excluded-lockfile-body") || strings.Contains(prompt, "excluded-generated-body") || !strings.Contains(prompt, "changed-package") {
		t.Fatal("Related evidence must contain necessary handwritten changes without excluded artifact bodies.")
	}
	for _, artifact := range []string{"excluded-vendor-body", "excluded-compiled-body", "excluded-binary-body"} {
		if strings.Contains(prompt, artifact) {
			t.Fatal("Related evidence must exclude vendored, compiled, and binary contents.")
		}
	}
}

func TestPreflightReviewOverridesAndAttributesControlGeneratedExclusions(t *testing.T) {
	file := classificationGitFile(t, "migration.sql", "SELECT 1;\n", "-- Code generated by sample; DO NOT EDIT.\nDROP TABLE users;\n")
	policy := policytest.Load(t)
	file.Attributes = map[string]string{"linguist-generated": "true", "custom": "value"}
	input := diff.ReviewInput{Files: []diff.FileContext{file}}
	decisions, unresolved, err := review.PlanFileAssessments(input, policy)
	if err != nil || len(unresolved) != 0 || len(decisions) != 1 || !decisions[0].PermitsContentExclusion() {
		t.Fatalf("The configured generated attribute must exclude generated SQL: %v", err)
	}
	identity := decisions[0].Identity
	file.Attributes = map[string]string{"custom": "value", "linguist-generated": "true"}
	reordered, _, err := review.PlanFileAssessments(diff.ReviewInput{Files: []diff.FileContext{file}}, policy)
	if err != nil || reordered[0].Identity != identity {
		t.Fatal("Attribute insertion order must not change the saved assessment identity.")
	}
	file.Attributes["linguist-generated"] = "false"
	input.Files[0] = file
	decisions, unresolved, err = review.PlanFileAssessments(input, policy)
	if err != nil || len(unresolved) != 0 || len(decisions) != 1 || decisions[0].Action != domain.FileActionReview || decisions[0].Identity == identity {
		t.Fatalf("An explicit false attribute must require direct SQL review with a new identity: %v", err)
	}
	file.Attributes["linguist-generated"] = "true"
	input.Files[0] = file
	override := classificationReviewOverridePolicy(t, file.Path)
	decisions, unresolved, err = review.PlanFileAssessments(input, override)
	if err != nil || len(unresolved) != 0 || len(decisions) != 1 || decisions[0].ContentReviewRequirement != domain.ContentReviewRequired {
		t.Fatalf("A configured override must require direct review: %v", err)
	}
	attemptedExclusion := classificationAssessment(t, file, override, domain.ContentReviewUnnecessary, domain.FileActionExclude, reviewrules.ContentGenerated)
	planned, _, err := review.PlanFileContentReview(input, []domain.FileAssessment{attemptedExclusion}, override)
	if err != nil {
		t.Fatal(err)
	}
	assertPlannedChangedRows(t, planned, file)
}

